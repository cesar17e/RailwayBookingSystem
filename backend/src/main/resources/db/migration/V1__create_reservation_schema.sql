-- PostgreSQL schema for the Spring Boot rewrite.
-- This migration is intentionally independent from the legacy MySQL dump.

CREATE TYPE user_role AS ENUM ('CUSTOMER', 'REPRESENTATIVE', 'ADMIN');
CREATE TYPE passenger_type AS ENUM ('ADULT', 'CHILD', 'SENIOR', 'DISABLED');
CREATE TYPE reservation_status AS ENUM ('ACTIVE', 'CANCELLED');
CREATE TYPE support_conversation_status AS ENUM ('OPEN', 'ANSWERED', 'CLOSED');

CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role user_role NOT NULL,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(60) NOT NULL,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    date_of_birth DATE,
    manager_id BIGINT REFERENCES app_user (id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT app_user_role_details_check CHECK (
        (role = 'CUSTOMER' AND date_of_birth IS NOT NULL AND manager_id IS NULL)
        OR (role = 'REPRESENTATIVE' AND date_of_birth IS NULL AND manager_id IS NOT NULL)
        OR (role = 'ADMIN' AND date_of_birth IS NULL AND manager_id IS NULL)
    ),
    CONSTRAINT app_user_not_own_manager_check CHECK (manager_id IS NULL OR manager_id <> id)
);

CREATE TABLE station (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_code VARCHAR(10) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    city VARCHAR(100) NOT NULL,
    state_code VARCHAR(2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT station_location_unique UNIQUE (name, city, state_code)
);

CREATE TABLE transit_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    line_code VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL UNIQUE,
    base_fare NUMERIC(10, 2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT transit_line_base_fare_check CHECK (base_fare >= 0)
);

CREATE TABLE transit_line_fare_policy (
    transit_line_id BIGINT NOT NULL REFERENCES transit_line (id) ON DELETE CASCADE,
    passenger_type passenger_type NOT NULL,
    discount_rate NUMERIC(5, 4) NOT NULL DEFAULT 0,
    PRIMARY KEY (transit_line_id, passenger_type),
    CONSTRAINT fare_policy_discount_rate_check CHECK (discount_rate >= 0 AND discount_rate <= 1)
);

CREATE TABLE transit_line_stop (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transit_line_id BIGINT NOT NULL REFERENCES transit_line (id) ON DELETE CASCADE,
    station_id BIGINT NOT NULL REFERENCES station (id) ON DELETE RESTRICT,
    stop_sequence INTEGER NOT NULL,
    arrival_time TIME,
    departure_time TIME,
    CONSTRAINT transit_line_stop_sequence_check CHECK (stop_sequence > 0),
    CONSTRAINT transit_line_stop_sequence_unique UNIQUE (transit_line_id, stop_sequence),
    CONSTRAINT transit_line_stop_station_unique UNIQUE (transit_line_id, station_id),
    CONSTRAINT transit_line_stop_time_order_check CHECK (
        arrival_time IS NULL OR departure_time IS NULL OR departure_time >= arrival_time
    )
);

CREATE TABLE train (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_code VARCHAR(30) NOT NULL UNIQUE,
    transit_line_id BIGINT NOT NULL REFERENCES transit_line (id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE train_schedule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_id BIGINT NOT NULL REFERENCES train (id) ON DELETE RESTRICT,
    departure_at TIMESTAMPTZ NOT NULL,
    arrival_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT train_schedule_time_order_check CHECK (arrival_at > departure_at)
);

CREATE TABLE schedule_stop (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id BIGINT NOT NULL REFERENCES train_schedule (id) ON DELETE CASCADE,
    station_id BIGINT NOT NULL REFERENCES station (id) ON DELETE RESTRICT,
    stop_sequence INTEGER NOT NULL,
    arrival_at TIMESTAMPTZ,
    departure_at TIMESTAMPTZ,
    CONSTRAINT schedule_stop_sequence_check CHECK (stop_sequence > 0),
    CONSTRAINT schedule_stop_sequence_unique UNIQUE (schedule_id, stop_sequence),
    CONSTRAINT schedule_stop_station_unique UNIQUE (schedule_id, station_id),
    CONSTRAINT schedule_stop_time_order_check CHECK (
        arrival_at IS NULL OR departure_at IS NULL OR departure_at >= arrival_at
    )
);

CREATE TABLE reservation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES app_user (id) ON DELETE RESTRICT,
    status reservation_status NOT NULL DEFAULT 'ACTIVE',
    passenger_type passenger_type NOT NULL,
    total_fare NUMERIC(10, 2) NOT NULL,
    booked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cancelled_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT reservation_total_fare_check CHECK (total_fare >= 0),
    CONSTRAINT reservation_cancellation_check CHECK (
        (status = 'ACTIVE' AND cancelled_at IS NULL)
        OR (status = 'CANCELLED' AND cancelled_at IS NOT NULL)
    )
);

CREATE TABLE reservation_leg (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL REFERENCES reservation (id) ON DELETE CASCADE,
    schedule_id BIGINT NOT NULL REFERENCES train_schedule (id) ON DELETE RESTRICT,
    origin_station_id BIGINT NOT NULL REFERENCES station (id) ON DELETE RESTRICT,
    destination_station_id BIGINT NOT NULL REFERENCES station (id) ON DELETE RESTRICT,
    leg_sequence INTEGER NOT NULL,
    fare_amount NUMERIC(10, 2) NOT NULL,
    CONSTRAINT reservation_leg_sequence_check CHECK (leg_sequence > 0),
    CONSTRAINT reservation_leg_station_check CHECK (origin_station_id <> destination_station_id),
    CONSTRAINT reservation_leg_fare_check CHECK (fare_amount >= 0),
    CONSTRAINT reservation_leg_sequence_unique UNIQUE (reservation_id, leg_sequence)
);

CREATE TABLE support_conversation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES app_user (id) ON DELETE RESTRICT,
    status support_conversation_status NOT NULL DEFAULT 'OPEN',
    subject VARCHAR(150) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE support_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES support_conversation (id) ON DELETE CASCADE,
    sender_id BIGINT NOT NULL REFERENCES app_user (id) ON DELETE RESTRICT,
    body TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT support_message_body_check CHECK (length(trim(body)) > 0)
);

CREATE FUNCTION set_updated_at() RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER app_user_set_updated_at
    BEFORE UPDATE ON app_user
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER station_set_updated_at
    BEFORE UPDATE ON station
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER transit_line_set_updated_at
    BEFORE UPDATE ON transit_line
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER train_set_updated_at
    BEFORE UPDATE ON train
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER train_schedule_set_updated_at
    BEFORE UPDATE ON train_schedule
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER reservation_set_updated_at
    BEFORE UPDATE ON reservation
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER support_conversation_set_updated_at
    BEFORE UPDATE ON support_conversation
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE INDEX app_user_manager_id_idx ON app_user (manager_id);
CREATE INDEX train_transit_line_id_idx ON train (transit_line_id);
CREATE INDEX train_schedule_train_departure_idx ON train_schedule (train_id, departure_at);
CREATE INDEX reservation_customer_booked_at_idx ON reservation (customer_id, booked_at DESC);
CREATE INDEX reservation_status_booked_at_idx ON reservation (status, booked_at);
CREATE INDEX reservation_leg_schedule_id_idx ON reservation_leg (schedule_id);
CREATE INDEX support_conversation_customer_updated_at_idx ON support_conversation (customer_id, updated_at DESC);
CREATE INDEX support_message_conversation_created_at_idx ON support_message (conversation_id, created_at);
